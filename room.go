// defaultQueueSize is the inbound queue capacity of a room whose type does not set one. Each room allocates its whole
// queue up front, so this is part of what every room costs, even an idle one.
const defaultQueueSize = 32

// Errors returned when submitting work to a room.
var (
	// ErrRoomClosed means the room no longer accepts input.
	ErrRoomClosed = errors.New("playhold: room closed")
	// ErrQueueFull means the room's inbound queue is full. The room keeps running.
	ErrQueueFull = errors.New("playhold: room queue full")
	// ErrRoomFull means the room has no free seat.
	ErrRoomFull = errors.New("playhold: room full")
)

// RoomID identifies one room for its whole life, across logs, snapshots and replays. It is generated by the
// runtime and never reused, so two matches can't be confused, even across nodes and restarts. Player-facing
// room codes are separate and can be reused.
type RoomID string

// newRoomID returns a UUIDv7: a timestamp followed by random data, so IDs sort by creation time and need no
// coordination between nodes.
func newRoomID() RoomID {
	return RoomID(uuid.NewV7().String())
}

// PlayerID identifies a player.
type PlayerID string

// CloseReason says why a room closed.
type CloseReason int

// Reasons a room can close.
const (
	// CloseRequested means the room was closed on purpose.
	CloseRequested CloseReason = iota + 1
	// CloseShutdown means the runtime is shutting down.
	CloseShutdown
	// ClosePanic means a handler panicked.
	ClosePanic
	// CloseInitFailed means the room's Init hook failed, so it never started.
	CloseInitFailed
	// CloseStuck means a turn ran for too long. The room's goroutine may still be running.
	CloseStuck
)

// String returns a short name for the reason.
func (r CloseReason) String() string {
	switch r {
	case CloseRequested:
		return "requested"
	case CloseShutdown:
		return "shutdown"
	case ClosePanic:
		return "panic"
	case CloseInitFailed:
		return "init failed"
	case CloseStuck:
		return "stuck"
	default:
		return fmt.Sprintf("unknown (%d)", int(r))
	}
}

// RoomContext gives a handler access to the room it runs in. It is valid only during the call it was passed to.
// It is not a context.Context.
type RoomContext struct {
	room   *Room
	player PlayerID
	// depth counts how many events led to this call. Zero means it wasn't caused by an event.
	depth int
	// viewing means this call is building a view, so it can't emit events.
	viewing bool
}

// RoomID returns the ID of the current room.
func (rc *RoomContext) RoomID() RoomID { return rc.room.id }

// Player returns the player whose input is being handled, or the player a view is being built for. It is empty in
// lifecycle hooks.
func (rc *RoomContext) Player() PlayerID { return rc.player }

// Rand returns the room's random numbers. Use it instead of math/rand, so a game can be reproduced from its seed.
func (rc *RoomContext) Rand() *rand.Rand { return rc.room.rng }

// Now returns the room's clock, which stays the same for a whole turn. Use it instead of time.Now, so a game can be
// reproduced.
func (rc *RoomContext) Now() time.Time { return rc.room.now }

// Players returns the room's seated players, in the order they arrived. A player keeps their seat when they
// disconnect. The result is a copy.
func (rc *RoomContext) Players() []PlayerID { return slices.Clone(rc.room.seats) }

// PlayerJoined is the event emitted when a player takes a new seat. It isn't emitted when a seated player
// reconnects.
type PlayerJoined struct {
	Player PlayerID
}

// CloseRoom asks the current room to close after this turn.
func (rc *RoomContext) CloseRoom() { rc.room.Close() }

// Emit sends a typed event to the modules subscribed to it with On. Events are delivered after the current
// handler returns, in the same turn, in module order. Events emitted while handling events queue behind them.
func (rc *RoomContext) Emit(event any) {
	if rc.viewing {
		panic(fmt.Sprintf("playhold: a view can't emit events; got %T", event))
	}
	rc.room.pending = append(rc.room.pending, pendingEvent{event: event, depth: rc.depth + 1})
}

// pendingEvent is an event waiting to be delivered.
type pendingEvent struct {
	event any
	depth int
}

// input is one unit of work for a room's goroutine.
type input struct {
	player PlayerID
	// run does the work on the room's goroutine.
	run func(rc *RoomContext) error
	// result, if set, receives the error from run on the room's goroutine. It is not called if run panics.
	result func(err error)
	// noViews skips sending views and saving a snapshot after this input, because it can't have changed the game.
	noViews bool
}

// viewSink receives a player's room state. Its method must not block.
type viewSink interface {
	SendState(state *wire.RoomState)
}

// Room is an isolated actor that owns its state and handles inputs one at a time on its own goroutine.
type Room struct {
	id     RoomID
	code   string // how players reach this room, if they do
	typ    *RoomType
	logger *slog.Logger
	onExit func(*Room)
	writer *snapshotWriter // nil if nothing is saved

	inbox chan input

	// Owned by the room's goroutine.
	slots    []any
	pending  []pendingEvent
	seats    []PlayerID
	viewers  map[PlayerID]viewSink
	rng      *rand.Rand
	rngState *rand.ChaCha8 // rng's source, which is what a snapshot saves
	clock    func() time.Time
	now      time.Time
	watchdog *time.Timer

	stuckTimeout time.Duration
	stuck        atomic.Bool // set if the watchdog gave up on this room's goroutine

	stopOnce   sync.Once
	stop       chan struct{} // closed only by requestStop
	stopReason CloseReason   // written before stop closes, read after

	finishOnce sync.Once
	done       chan struct{}
	reason     CloseReason // written before done closes, read after
}

func newRoom(id RoomID, typ *RoomType, cfg *Config, onExit func(*Room)) *Room {
	size := typ.cfg.QueueSize
	if size <= 0 {
		size = defaultQueueSize
	}
	rngState := rand.NewChaCha8(cfg.NewSeed())
	return &Room{
		id:     id,
		typ:    typ,
		logger: cfg.Logger.With("room", string(id), "room_type", typ.cfg.Name),
		onExit: onExit,
		inbox:  make(chan input, size),
		slots:  make([]any, typ.slotCount),

		viewers:      make(map[PlayerID]viewSink),
		rng:          rand.New(rngState), //nolint:gosec // ChaCha8 is strong, and seeded from crypto/rand by default
		rngState:     rngState,
		clock:        cfg.Now,
		stuckTimeout: cfg.StuckTimeout,

		stop: make(chan struct{}),
		done: make(chan struct{}),
	}
}

// ID returns the room's ID.
func (r *Room) ID() RoomID { return r.id }

// Close asks the room to close and returns without waiting. Inputs still queued are dropped.
func (r *Room) Close() { r.requestStop(CloseRequested) }

// Done is closed when the room has finished.
func (r *Room) Done() <-chan struct{} { return r.done }

// Wait blocks until the room has finished and returns why it closed.
func (r *Room) Wait() CloseReason {
	<-r.done
	return r.reason
}

func (r *Room) requestStop(reason CloseReason) {
	r.stopOnce.Do(func() {
		r.stopReason = reason
		close(r.stop)
	})
}

// submit queues an input without blocking.
func (r *Room) submit(in input) error {
	select {
	case <-r.stop:
		return ErrRoomClosed
	default:
	}
	select {
	case r.inbox <- in:
		return nil
	default:
		return ErrQueueFull
	}
}

// dispatch queues a message for the handler registered by the named module. The result, if set, receives the
// handler's error on the room's goroutine.
func (r *Room) dispatch(player PlayerID, module string, id uint32, payload []byte, result func(error)) error {
	return r.submit(input{player: player, result: result, run: func(rc *RoomContext) error {
		handler, ok := r.typ.handlers[handlerKey{module: module, id: id}]
		if !ok {
			return fmt.Errorf("%w: module %q message %d", ErrUnknownMessage, module, id)
		}
		return handler(rc, payload)
	}})
}

// seat queues a request to seat the player, who keeps any seat they already have. From then on the sink, if set,
// receives the player's views, starting with a full view at the end of this turn. The result receives the outcome
// on the room's goroutine. It isn't called if the room closes first.
func (r *Room) seat(player PlayerID, sink viewSink, result func(error)) error {
	return r.submit(input{player: player, result: result, run: func(rc *RoomContext) error {
		if !slices.Contains(r.seats, player) {
			if limit := r.typ.cfg.MaxPlayers; limit > 0 && len(r.seats) >= limit {
				return ErrRoomFull
			}
			r.seats = append(r.seats, player)
			rc.Emit(PlayerJoined{Player: player})
		}
		if sink != nil {
			r.viewers[player] = sink
		}
		return nil
	}})
}

// removeViewer stops sending views to the sink, unless the player has since moved to a newer one. If the request
// can't be queued, the old sink stays until it is replaced or the room closes, which only wastes a little work.
func (r *Room) removeViewer(player PlayerID, sink viewSink) {
	_ = r.submit(input{player: player, noViews: true, run: func(_ *RoomContext) error {
		if r.viewers[player] == sink {
			delete(r.viewers, player)
		}
		return nil
	}})
}

// sendViews gives each connected player a full view of the room, in one frame.
func (r *Room) sendViews() {
	if len(r.typ.views) == 0 {
		return
	}
	for _, player := range r.seats {
		if sink, ok := r.viewers[player]; ok {
			sink.SendState(r.stateFor(player))
		}
	}
}

func (r *Room) stateFor(player PlayerID) *wire.RoomState {
	rc := &RoomContext{room: r, player: player, viewing: true}
	state := &wire.RoomState{Views: make([]*wire.ModuleView, 0, len(r.typ.views))}
	for i := range r.typ.views {
		view := &r.typ.views[i]
		if data, ok := view.build(rc); ok {
			state.Views = append(state.Views, &wire.ModuleView{Module: view.module, View: data})
		}
	}
	return state
}

// startWork reads the clock and starts the stuck timer for one turn. The caller stops the timer afterward.
func (r *Room) startWork() {
	r.now = r.clock()
	r.watchdog.Reset(r.stuckTimeout)
}

// abandon closes a room whose goroutine has run for too long. Go can't kill that goroutine, so if it ever wakes it
// finds the room closed and ends without touching anything outside the room.
func (r *Room) abandon() {
	r.logger.Error("room stuck, closing it", "timeout", r.stuckTimeout)
	r.stuck.Store(true)
	r.requestStop(CloseStuck)
	if r.writer != nil {
		r.writer.forget(string(r.id))
	}
	r.finish(CloseStuck)
}

// saveSnapshot encodes the room on its own goroutine, so the copy is consistent, and leaves the writing to the writer.
// A room that can't be encoded panics, closing it, rather than carrying on with nothing saved.
func (r *Room) saveSnapshot() {
	if r.writer == nil {
		return
	}
	rngState, err := r.rngState.MarshalBinary()
	if err != nil {
		panic(fmt.Sprintf("playhold: room's random numbers can't be saved: %v", err))
	}
	snapshot := &wire.RoomSnapshot{
		Seats:          make([]string, 0, len(r.seats)),
		RngState:       rngState,
		ClockUnixNanos: r.now.UnixNano(),
		Modules:        make([]*wire.ModuleSnapshot, 0, len(r.typ.snapshots)),
	}
	for _, player := range r.seats {
		snapshot.Seats = append(snapshot.Seats, string(player))
	}
	for i := range r.typ.snapshots {
		module := &r.typ.snapshots[i]
		state, err := module.encode(r.slots[module.index])
		if err != nil {
			panic(fmt.Sprintf("playhold: module %q state can't be saved: %v", module.module, err))
		}
		snapshot.Modules = append(snapshot.Modules, &wire.ModuleSnapshot{
			Module:  module.module,
			Version: uint32(module.version), //nolint:gosec // a small number the module chose
			State:   state,
		})
	}
	data, err := proto.Marshal(snapshot)
	if err != nil {
		panic(fmt.Sprintf("playhold: room can't be saved: %v", err))
	}
	r.writer.save(store.RoomRecord{ID: string(r.id), Code: r.code, RoomType: r.typ.cfg.Name, Data: data})
}

// finishSnapshot decides what stays saved when a room closes. A shutdown is the only reason to keep it: the room comes
// back when the server does. Every other close means the room is over.
func (r *Room) finishSnapshot(reason CloseReason) {
	if r.writer == nil || r.stuck.Load() {
		return
	}
	if reason != CloseShutdown {
		r.writer.forget(string(r.id))
		return
	}
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("saving room at shutdown panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.saveSnapshot()
}

// closed reports whether the room has finished.
func (r *Room) closed() bool {
	select {
	case <-r.done:
		return true
	default:
		return false
	}
}

// runInit creates module state and runs the Init hook on the calling goroutine, before the room's own
// goroutine starts.
func (r *Room) runInit() (panicErr error) {
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("room init panicked", "panic", v, "stack", string(debug.Stack()))
			panicErr = fmt.Errorf("playhold: room init panicked: %v", v)
		}
	}()
	r.now = r.clock()
	for _, slot := range r.typ.slots {
		r.slots[slot.index] = slot.init()
	}
	if r.typ.cfg.Init != nil {
		if err := r.typ.cfg.Init(&RoomContext{room: r}); err != nil {
			return err // the room never starts, so its events are dropped
		}
	}
	r.deliverEvents("")
	r.saveSnapshot()
	return nil
}

// deliverEvents delivers pending events in order, including any emitted along the way.
func (r *Room) deliverEvents(player PlayerID) {
	for len(r.pending) > 0 {
		next := r.pending[0]
		r.pending = r.pending[1:]
		if next.depth > maxEventDepth {
			panic(fmt.Sprintf("playhold: events triggered more than %d further events; last was %T", maxEventDepth, next.event))
		}
		rc := &RoomContext{room: r, player: player, depth: next.depth}
		for _, handler := range r.typ.events[reflect.TypeOf(next.event)] {
			handler(rc, next.event)
		}
	}
	r.pending = nil
}

// run is the room's goroutine.
func (r *Room) run() {
	r.watchdog = time.AfterFunc(r.stuckTimeout, r.abandon)
	r.watchdog.Stop()

	reason := r.loop()
	r.callClose(reason)
	r.finishSnapshot(reason)
	r.finish(reason)
}

func (r *Room) loop() CloseReason {
	for {
		// Stopping takes priority over queued inputs.
		select {
		case <-r.stop:
			return r.stopReason
		default:
		}
		select {
		case <-r.stop:
			return r.stopReason
		case in := <-r.inbox:
			if panicked := r.turn(in); panicked {
				return ClosePanic
			}
		}
	}
}

// turn handles one input. A panic is contained here, so it closes only this room.
func (r *Room) turn(in input) (panicked bool) {
	defer func() {
		if v := recover(); v != nil {
			panicked = true
			r.logger.Error("room handler panicked", "player", string(in.player), "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.startWork()
	defer r.watchdog.Stop()

	err := in.run(&RoomContext{room: r, player: in.player})
	r.deliverEvents(in.player)
	if r.stuck.Load() {
		return false // players were already told the room closed
	}
	if in.result != nil {
		in.result(err)
	}
	if !in.noViews {
		r.sendViews()
		r.saveSnapshot()
	}
	return false
}

func (r *Room) callClose(reason CloseReason) {
	r.pending = nil // events left over from a panicked turn are dropped
	if r.typ.cfg.Close == nil || r.stuck.Load() {
		return
	}
	r.startWork()
	defer r.watchdog.Stop()
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("room close hook panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.typ.cfg.Close(&RoomContext{room: r}, reason)
	r.deliverEvents("")
}

// finish marks the room as finished. It also releases anyone waiting on a room that never started.
func (r *Room) finish(reason CloseReason) {
	r.finishOnce.Do(func() {
		r.requestStop(reason)
		r.reason = reason
		r.onExit(r)
		close(r.done)
	})
}
