// defaultQueueSize is the inbound queue capacity of a room whose type does not set one. Each room allocates its whole
// queue up front, so this is part of what every room costs, even an idle one.
const defaultQueueSize = 32

// Errors returned when submitting work to a room.
var (
	// ErrRoomClosed means the room no longer accepts input.
	ErrRoomClosed = errors.New("playhold: room closed")
	// ErrQueueFull means the room's inbound queue is full. The room keeps running.
	ErrQueueFull = errors.New("playhold: room queue full")
	// ErrRoomFull means the room has no free seat.
	ErrRoomFull = errors.New("playhold: room full")
	// ErrMessageFailed means handling the message crashed the room, which went back to its last snapshot, so the
	// message had no effect.
	ErrMessageFailed = errors.New("playhold: the server couldn't handle that message")
)

// RoomID identifies one room for its whole life, across logs, snapshots and replays. It is generated by the
// runtime and never reused, so two matches can't be confused, even across nodes and restarts. Player-facing
// room codes are separate and can be reused.
type RoomID string

// newRoomID returns a UUIDv7: a timestamp followed by random data, so IDs sort by creation time and need no
// coordination between nodes.
func newRoomID() RoomID {
	return RoomID(uuid.NewV7().String())
}

// PlayerID identifies a player.
type PlayerID string

// CloseReason says why a room closed.
type CloseReason int

// Reasons a room can close.
const (
	// CloseRequested means the room was closed on purpose.
	CloseRequested CloseReason = iota + 1
	// CloseShutdown means the runtime is shutting down.
	CloseShutdown
	// ClosePanic means a handler panicked.
	ClosePanic
	// CloseInitFailed means the room's Init hook failed, so it never started.
	CloseInitFailed
	// CloseStuck means a turn ran for too long. The room's goroutine may still be running.
	CloseStuck
	// CloseInactive means no player sent anything to the room for longer than the server's InactiveRoomTimeout.
	CloseInactive
)

// String returns a short name for the reason.
func (r CloseReason) String() string {
	switch r {
	case CloseRequested:
		return "requested"
	case CloseShutdown:
		return "shutdown"
	case ClosePanic:
		return "panic"
	case CloseInitFailed:
		return "init failed"
	case CloseStuck:
		return "stuck"
	case CloseInactive:
		return "inactive"
	default:
		return fmt.Sprintf("unknown (%d)", int(r))
	}
}

// RoomContext gives a handler access to the room it runs in. It is valid only during the call it was passed to.
// It is not a context.Context.
type RoomContext struct {
	room   *Room
	player PlayerID
	// depth counts how many events led to this call. Zero means it wasn't caused by an event.
	depth int
	// viewing means this call is building a view, so it can't emit events.
	viewing bool
}

// RoomID returns the ID of the current room.
func (rc *RoomContext) RoomID() RoomID { return rc.room.id }

// Player returns the player whose input is being handled, or the player a view is being built for. It is empty in
// lifecycle hooks.
func (rc *RoomContext) Player() PlayerID { return rc.player }

// Rand returns the room's random numbers. Use it instead of math/rand, so a game can be reproduced from its seed.
func (rc *RoomContext) Rand() *rand.Rand { return rc.room.rng }

// Now returns the room's clock, which stays the same for a whole turn. Use it instead of time.Now, so a game can be
// reproduced.
func (rc *RoomContext) Now() time.Time { return rc.room.now }

// Players returns the room's seated players, in the order they arrived. A player keeps their seat when they
// disconnect. The result is a copy.
func (rc *RoomContext) Players() []PlayerID { return slices.Clone(rc.room.seats) }

// PlayerJoined is the event emitted when a player takes a new seat. It isn't emitted when a seated player
// reconnects.
type PlayerJoined struct {
	Player PlayerID
}

// CloseRoom asks the current room to close after this turn.
func (rc *RoomContext) CloseRoom() { rc.room.Close() }

// Emit sends a typed event to the modules subscribed to it with On. Events are delivered after the current
// handler returns, in the same turn, in module order. Events emitted while handling events queue behind them.
func (rc *RoomContext) Emit(event any) {
	if rc.viewing {
		panic(fmt.Sprintf("playhold: a view can't emit events; got %T", event))
	}
	rc.room.pending = append(rc.room.pending, pendingEvent{event: event, depth: rc.depth + 1})
}

// pendingEvent is an event waiting to be delivered.
type pendingEvent struct {
	event any
	depth int
}

// input is one unit of work for a room's goroutine. It's passed by value, so keep it under 80 bytes: the small fields go
// last, together, where they share one word instead of each padding out their own.
type input struct {
	player PlayerID
	// run does the work on the room's goroutine.
	run func(rc *RoomContext) error
	// result, if set, receives the error from run on the room's goroutine. It is not called if run panics.
	result func(err error)
	// timerEvent names the event, if a timer started this input, so a crash can say what caused it.
	timerEvent string
	// module and id name the message, if a player sent one, so a slow turn can say which.
	module string
	id     uint32
	// noViews skips sending views and saving a snapshot after this input, because it can't have changed the game.
	noViews bool
}

// viewSink receives a player's room state. Its method must not block.
type viewSink interface {
	SendState(state *wire.RoomState)
}

// Room is an isolated actor that owns its state and handles inputs one at a time on its own goroutine.
type Room struct {
	id     RoomID
	code   string // how players reach this room, if they do
	typ    *RoomType
	logger *slog.Logger
	onExit func(*Room)
	writer *snapshotWriter // nil if nothing is saved

	// restart replaces this room with a copy from its last snapshot after a crash, and reports whether it did. Nil
	// means the room just closes.
	restart      func(*Room) bool
	lastSnapshot atomic.Pointer[[]byte] // read after a stuck room's goroutine has been given up on

	inbox chan input

	// Owned by the room's goroutine.
	slots    []any
	pending  []pendingEvent
	seats    []PlayerID
	viewers  map[PlayerID]viewSink
	rng      *rand.Rand
	rngState *rand.ChaCha8 // rng's source, which is what a snapshot saves
	clock    func() time.Time
	now      time.Time
	watchdog *time.Timer

	// Also owned by the room's goroutine.
	timers      []roomTimer // soonest first
	lastTimerID TimerID
	alarm       *time.Timer
	alarmSet    bool
	alarmDue    time.Time

	// Also owned by the room's goroutine, for a snapshot interval.
	savedAt   time.Time   // the room's clock at its last save
	saveTimer *time.Timer // runs while a change is waiting for the interval to pass
	saveSet   bool

	// Also owned by the room's goroutine.
	grace  time.Duration // how long a player has to come back. Zero means nothing tracks their connections
	graces []graceTimer  // soonest first
	away   []PlayerID    // their PlayerDisconnected has fired

	// Also owned by the room's goroutine. Zero inactive means the room never closes for inactivity.
	admit       func() bool // whether a new player may take a seat now; nil always allows
	inactive    time.Duration
	inactiveDue time.Time // the room closes then, unless a player sends something first

	stuckTimeout time.Duration
	slowTurn     time.Duration // a turn longer than this is logged; zero logs none
	stuck        atomic.Bool   // set if the watchdog gave up on this room's goroutine, only while holding gate
	draining     atomic.Bool   // set if the server is about to stop, so no new players

	// gate is held while something leaves the room: an answer to a sender, a snapshot or views. Once the watchdog has
	// given up on the room, nothing its goroutine does afterward gets out, even if it was already on its way.
	gate sync.Mutex

	stopOnce   sync.Once
	stop       chan struct{} // closed only by requestStop
	stopReason CloseReason   // written before stop closes, read after

	finishOnce sync.Once
	done       chan struct{}
	reason     CloseReason // written before done closes, read after

	// onStuck, if set, hears about the room once the watchdog has given up on it. exited closes when the room's
	// goroutine really returns, which for a stuck room can be much later than done, or never.
	onStuck func(*Room)
	exited  chan struct{}

	// The crash journal, if any. journalBuf is the room goroutine's; journalSeq is the running turn's entry, zero between
	// turns, and also read by the watchdog.
	journal    *journal
	journalBuf []byte
	journalSeq atomic.Uint64
}

func newRoom(id RoomID, typ *RoomType, cfg *Config, onExit func(*Room)) *Room {
	size := typ.cfg.QueueSize
	if size <= 0 {
		size = defaultQueueSize
	}
	rngState := rand.NewChaCha8(cfg.NewSeed())
	return &Room{
		id:     id,
		typ:    typ,
		logger: cfg.Logger.With("room", string(id), "room_type", typ.cfg.Name),
		onExit: onExit,
		inbox:  make(chan input, size),
		slots:  make([]any, typ.slotCount),

		viewers:      make(map[PlayerID]viewSink),
		rng:          rand.New(rngState), //nolint:gosec // ChaCha8 is strong, and seeded from crypto/rand by default
		rngState:     rngState,
		clock:        cfg.Now,
		stuckTimeout: cfg.StuckTimeout,
		slowTurn:     cfg.SlowTurn.duration(),

		stop:   make(chan struct{}),
		done:   make(chan struct{}),
		exited: make(chan struct{}),
	}
}

// ID returns the room's ID.
func (r *Room) ID() RoomID { return r.id }

// Close asks the room to close and returns without waiting. Inputs still queued are dropped.
func (r *Room) Close() { r.requestStop(CloseRequested) }

// Done is closed when the room has finished.
func (r *Room) Done() <-chan struct{} { return r.done }

// Wait blocks until the room has finished and returns why it closed.
func (r *Room) Wait() CloseReason {
	<-r.done
	return r.reason
}

func (r *Room) requestStop(reason CloseReason) {
	r.stopOnce.Do(func() {
		r.stopReason = reason
		close(r.stop)
	})
}

// submit queues an input without blocking.
func (r *Room) submit(in input) error {
	select {
	case <-r.stop:
		return ErrRoomClosed
	default:
	}
	select {
	case r.inbox <- in:
		return nil
	default:
		return ErrQueueFull
	}
}

// submitWait is submit for inputs that can't be refused, because no client is going to send them again. It waits for
// space in the queue, which holds up only the caller, until the room takes the input or closes.
func (r *Room) submitWait(in input) error {
	select {
	case <-r.stop:
		return ErrRoomClosed
	default:
	}
	select {
	case r.inbox <- in:
		return nil
	case <-r.stop:
		return ErrRoomClosed
	}
}

// dispatch queues a message for the handler registered by the named module. The result, if set, receives the
// handler's error on the room's goroutine.
func (r *Room) dispatch(player PlayerID, module string, id uint32, payload []byte, result func(error)) error {
	return r.submit(input{player: player, result: result, module: module, id: id, run: func(rc *RoomContext) error {
		if r.journal != nil {
			r.journalBegin(&JournalEntry{Player: player, Module: module, MessageID: id, Size: len(payload), Payload: payload})
		}
		r.playerActive()
		handler, ok := r.typ.handlers[handlerKey{module: module, id: id}]
		if !ok {
			return fmt.Errorf("%w: module %q message %d", ErrUnknownMessage, module, id)
		}
		return handler(rc, payload)
	}})
}

// seat queues a request to seat the player, who keeps any seat they already have. From then on the sink, if set,
// receives the player's views, starting with a full view at the end of this turn. The result receives the outcome
// on the room's goroutine. It isn't called if the room closes first. It waits for space in the queue, because a busy
// room must not turn away players coming back to it after a restart, all at once.
func (r *Room) seat(player PlayerID, sink viewSink, result func(error)) error {
	return r.submitWait(input{player: player, result: result, run: func(rc *RoomContext) error {
		r.playerActive()
		if !slices.Contains(r.seats, player) {
			if r.draining.Load() {
				return ErrDraining
			}
			if r.admit != nil && !r.admit() {
				return ErrOverloaded // a player who already has a seat is never refused
			}
			if limit := r.typ.cfg.MaxPlayers; limit > 0 && len(r.seats) >= limit {
				return ErrRoomFull
			}
			r.seats = append(r.seats, player)
			rc.Emit(PlayerJoined{Player: player})
		}
		if sink != nil {
			r.viewers[player] = sink
			r.playerBack(rc, player)
		}
		return nil
	}})
}

// removeViewer stops sending views to the sink and starts the player's grace period, unless the player has since moved
// to a newer sink. It waits for space in the queue, because a lost request would mean the game never hears they left.
func (r *Room) removeViewer(player PlayerID, sink viewSink) {
	_ = r.submitWait(input{player: player, noViews: true, run: func(_ *RoomContext) error {
		if r.viewers[player] == sink {
			delete(r.viewers, player)
			r.startGrace(player)
		}
		return nil
	}})
}

// sendViews gives each connected player a full view of the room, in one frame. The views run game code, so they're built
// before the gate, which only holds the sending.
func (r *Room) sendViews() {
	if len(r.typ.views) == 0 {
		return
	}
	type delivery struct {
		sink  viewSink
		state *wire.RoomState
	}
	out := make([]delivery, 0, len(r.seats))
	for _, player := range r.seats {
		if sink, ok := r.viewers[player]; ok {
			out = append(out, delivery{sink: sink, state: r.stateFor(player)})
		}
	}
	r.publish(func() {
		for i := range out {
			out[i].sink.SendState(out[i].state)
		}
	})
}

// publish runs fn, which hands something to the world outside the room, unless the watchdog has given up on the room.
// fn must not block or run game code, since abandon waits for the gate.
func (r *Room) publish(fn func()) {
	r.gate.Lock()
	defer r.gate.Unlock()
	if !r.stuck.Load() {
		fn()
	}
}

func (r *Room) stateFor(player PlayerID) *wire.RoomState {
	rc := &RoomContext{room: r, player: player, viewing: true}
	state := &wire.RoomState{Views: make([]*wire.ModuleView, 0, len(r.typ.views))}
	for i := range r.typ.views {
		view := &r.typ.views[i]
		if data, ok := view.build(rc); ok {
			state.Views = append(state.Views, &wire.ModuleView{Module: view.module, View: data})
		}
	}
	return state
}

// startWork reads the clock and starts the stuck timer for one turn. The caller stops the timer afterward.
func (r *Room) startWork() {
	r.now = r.clock()
	r.watchdog.Reset(r.stuckTimeout)
}

// abandon closes a room whose goroutine has run for too long. Go can't kill that goroutine, so if it ever wakes it
// finds the room closed and ends without touching anything outside the room.
func (r *Room) abandon() {
	r.logger.Error("room stuck, closing it", "timeout", r.stuckTimeout)
	r.gate.Lock() // waits for anything already on its way out, and stops everything after it
	r.stuck.Store(true)
	r.gate.Unlock()
	r.journalMark(JournalStuck, true)
	r.requestStop(CloseStuck)
	r.finish(CloseStuck)
	if r.onStuck != nil {
		r.onStuck(r)
	}
}

// applySnapshot fills a new room from a saved one. A module with no saved state, one added since, starts fresh. A
// module's load function is game code, so a panic there is reported as a room that can't be restored.
func (r *Room) applySnapshot(data []byte, policy TimersAfterRestart) (err error) {
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("restoring room panicked", "panic", v, "stack", string(debug.Stack()))
			err = fmt.Errorf("playhold: restoring room panicked: %v", v)
		}
	}()

	snapshot := &wire.RoomSnapshot{}
	if err := proto.Unmarshal(data, snapshot); err != nil {
		return fmt.Errorf("playhold: decoding room: %w", err)
	}
	if err := r.rngState.UnmarshalBinary(snapshot.GetRngState()); err != nil {
		return fmt.Errorf("playhold: restoring random numbers: %w", err)
	}
	r.now = time.Unix(0, snapshot.GetClockUnixNanos()).UTC()
	r.seats = make([]PlayerID, 0, len(snapshot.GetSeats()))
	for _, player := range snapshot.GetSeats() {
		r.seats = append(r.seats, PlayerID(player))
	}
	for _, player := range snapshot.GetAway() {
		r.away = append(r.away, PlayerID(player))
	}
	if err := r.decodeTimers(snapshot.GetTimers()); err != nil {
		return err
	}
	r.lastTimerID = TimerID(snapshot.GetLastTimerId())
	r.applyRestartPolicy(policy)

	for _, slot := range r.typ.slots {
		r.slots[slot.index] = slot.init()
	}
	for i := range r.typ.snapshots {
		module := &r.typ.snapshots[i]
		saved := findModule(snapshot, module.module)
		if saved == nil {
			continue
		}
		state, err := module.load(int(saved.GetVersion()), saved.GetState())
		if err != nil {
			return fmt.Errorf("playhold: module %q: %w", module.module, err)
		}
		r.slots[module.index] = state
	}
	r.lastSnapshot.Store(&data)
	return nil
}

func findModule(snapshot *wire.RoomSnapshot, module string) *wire.ModuleSnapshot {
	for _, saved := range snapshot.GetModules() {
		if saved.GetModule() == module {
			return saved
		}
	}
	return nil
}

// saveSnapshot encodes the room on its own goroutine, so the copy is consistent, and leaves the writing to the writer.
// A room that can't be encoded panics, closing it, rather than carrying on with nothing saved.
func (r *Room) saveSnapshot() {
	if r.writer == nil {
		return
	}
	r.savedAt = r.now
	if r.saveSet { // this save includes the change that was waiting
		r.saveTimer.Stop()
		r.saveSet = false
	}
	rngState, err := r.rngState.MarshalBinary()
	if err != nil {
		panic(fmt.Sprintf("playhold: room's random numbers can't be saved: %v", err))
	}
	snapshot := &wire.RoomSnapshot{
		Seats:          make([]string, 0, len(r.seats)),
		RngState:       rngState,
		ClockUnixNanos: r.now.UnixNano(),
		Modules:        make([]*wire.ModuleSnapshot, 0, len(r.typ.snapshots)),
		Timers:         r.encodeTimers(),
		LastTimerId:    uint64(r.lastTimerID),
	}
	for _, player := range r.seats {
		snapshot.Seats = append(snapshot.Seats, string(player))
	}
	for _, player := range r.away {
		snapshot.Away = append(snapshot.Away, string(player))
	}
	for i := range r.typ.snapshots {
		module := &r.typ.snapshots[i]
		state, err := module.encode(r.slots[module.index])
		if err != nil {
			panic(fmt.Sprintf("playhold: module %q state can't be saved: %v", module.module, err))
		}
		snapshot.Modules = append(snapshot.Modules, &wire.ModuleSnapshot{
			Module:  module.module,
			Version: uint32(module.version), //nolint:gosec // a small number the module chose
			State:   state,
		})
	}
	data, err := proto.Marshal(snapshot)
	if err != nil {
		panic(fmt.Sprintf("playhold: room can't be saved: %v", err))
	}
	r.publish(func() {
		r.lastSnapshot.Store(&data)
		r.writer.save(store.RoomRecord{ID: string(r.id), Code: r.code, RoomType: r.typ.cfg.Name, Data: data})
	})
}

// saveChange saves the room after a turn changed it. With a snapshot interval, a change that comes sooner than the
// interval after the last save waits for it to pass, and the changes made meanwhile are saved together. While the
// server drains, every change is saved at once.
func (r *Room) saveChange() {
	if r.writer == nil {
		return
	}
	interval := r.writer.interval
	if interval <= 0 || r.draining.Load() {
		r.saveSnapshot()
		return
	}
	if r.saveSet {
		return // already waiting
	}
	if since := r.now.Sub(r.savedAt); since < interval {
		r.saveTimer.Reset(interval - since)
		r.saveSet = true
		return
	}
	r.saveSnapshot()
}

// saveWaiting saves the changes a snapshot interval held back. Encoding runs game code, so it's watched like a turn, and
// a panic closes the room like one.
func (r *Room) saveWaiting() (panicked bool) {
	defer func() {
		if v := recover(); v != nil {
			panicked = true
			r.logger.Error("saving room panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.saveSet = false
	r.startWork()
	defer r.watchdog.Stop()
	r.saveSnapshot()
	return false
}

// finishSnapshot decides what stays saved when a room closes on its goroutine. A shutdown keeps it, because the room
// comes back when the server does, and a close on purpose means the room is over. A crash is decided in finish.
func (r *Room) finishSnapshot(reason CloseReason) {
	if r.writer == nil || reason == ClosePanic || r.stuck.Load() {
		return
	}
	if reason != CloseShutdown {
		r.publish(func() { r.writer.forget(string(r.id)) })
		return
	}
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("saving room at shutdown panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.now = r.clock() // so a pause after this counts only the time the server was really down
	r.saveSnapshot()
}

// closed reports whether the room has finished.
func (r *Room) closed() bool {
	select {
	case <-r.done:
		return true
	default:
		return false
	}
}

// runInit creates module state and runs the Init hook on the calling goroutine, before the room's own
// goroutine starts.
func (r *Room) runInit() (panicErr error) {
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("room init panicked", "panic", v, "stack", string(debug.Stack()))
			panicErr = fmt.Errorf("playhold: room init panicked: %v", v)
		}
	}()
	r.now = r.clock()
	for _, slot := range r.typ.slots {
		r.slots[slot.index] = slot.init()
	}
	if r.typ.cfg.Init != nil {
		if err := r.typ.cfg.Init(&RoomContext{room: r}); err != nil {
			return err // the room never starts, so its events are dropped
		}
	}
	r.deliverEvents("")
	r.saveSnapshot()
	return nil
}

// deliverEvents delivers pending events in order, including any emitted along the way.
func (r *Room) deliverEvents(player PlayerID) {
	for len(r.pending) > 0 {
		next := r.pending[0]
		r.pending = r.pending[1:]
		if next.depth > maxEventDepth {
			panic(fmt.Sprintf("playhold: events triggered more than %d further events; last was %T", maxEventDepth, next.event))
		}
		rc := &RoomContext{room: r, player: player, depth: next.depth}
		for _, handler := range r.typ.events[reflect.TypeOf(next.event)] {
			handler(rc, next.event)
		}
	}
	r.pending = nil
}

// run is the room's goroutine.
func (r *Room) run() {
	defer close(r.exited)
	r.watchdog = time.AfterFunc(r.stuckTimeout, r.abandon)
	r.watchdog.Stop()
	r.alarm = time.NewTimer(r.stuckTimeout)
	r.alarm.Stop()
	defer r.alarm.Stop()
	r.saveTimer = time.NewTimer(r.stuckTimeout)
	r.saveTimer.Stop()
	defer r.saveTimer.Stop()

	reason := r.loop()
	r.callClose(reason)
	r.finishSnapshot(reason)
	r.finish(reason)
}

func (r *Room) loop() CloseReason {
	for {
		// Stopping takes priority over queued inputs.
		select {
		case <-r.stop:
			return r.stopReason
		default:
		}
		r.armAlarm()
		select {
		case <-r.stop:
			return r.stopReason
		case in := <-r.inbox:
			if panicked := r.turn(in); panicked {
				r.reportFailedInput(in)
				return ClosePanic
			}
		case <-r.alarm.C:
			if panicked := r.fireNext(); panicked {
				return ClosePanic
			}
		case <-r.saveTimer.C:
			if panicked := r.saveWaiting(); panicked {
				return ClosePanic
			}
		}
	}
}

// reportFailedInput tells the sender their input had no effect. Without a restart, the room closing says enough.
func (r *Room) reportFailedInput(in input) {
	if r.restart == nil || in.result == nil {
		return
	}
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("reporting a failed input panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	in.result(ErrMessageFailed)
}

// turn handles one input. A panic is contained here, so it closes only this room.
func (r *Room) turn(in input) (panicked bool) {
	defer func() {
		if v := recover(); v != nil {
			panicked = true
			r.logger.Error("room handler panicked",
				"player", string(in.player), "timer_event", in.timerEvent, "panic", v, "stack", string(debug.Stack()))
		}
		if panicked {
			r.journalMark(JournalPanicked, true)
		} else {
			r.journalMark(JournalDone, true) // nothing, if the watchdog already wrote stuck
		}
	}()
	r.startWork()
	defer r.watchdog.Stop()

	started := time.Now() // the real time, whatever clock the room reads
	err := in.run(&RoomContext{room: r, player: in.player})
	r.deliverEvents(in.player)
	r.journalMark(JournalHandled, false)
	r.reportSlowTurn(&in, time.Since(started))
	if r.stuck.Load() {
		return false // players were already told the room closed, and nothing below would get out anyway
	}
	if in.result != nil {
		r.publish(func() { in.result(err) })
	}
	if !in.noViews {
		// Saved first, so a player can't see a move that a clean stop right afterward would lose. A stop always saves a
		// change that a snapshot interval is holding back.
		r.saveChange()
		r.sendViews()
	}
	return false
}

// reportSlowTurn logs a turn that took longer than the time budget: the room carries on, but its game code is slow
// enough to hold up the players in it.
func (r *Room) reportSlowTurn(in *input, took time.Duration) {
	if r.slowTurn <= 0 || took <= r.slowTurn {
		return
	}
	r.logger.Warn("slow turn", "took", took, "budget", r.slowTurn,
		"player", string(in.player), "module", in.module, "message_id", in.id, "timer_event", in.timerEvent)
}

func (r *Room) callClose(reason CloseReason) {
	r.pending = nil // events left over from a panicked turn are dropped
	if r.typ.cfg.Close == nil || r.stuck.Load() {
		return
	}
	if reason == ClosePanic && r.restart != nil {
		return // the room isn't over: a copy is about to take its place, and it would be half-updated anyway
	}
	r.startWork()
	defer r.watchdog.Stop()
	defer func() {
		if v := recover(); v != nil {
			r.logger.Error("room close hook panicked", "panic", v, "stack", string(debug.Stack()))
		}
	}()
	r.typ.cfg.Close(&RoomContext{room: r}, reason)
	r.deliverEvents("")
}

// finish marks the room as finished. It also releases anyone waiting on a room that never started.
func (r *Room) finish(reason CloseReason) {
	r.finishOnce.Do(func() {
		r.requestStop(reason)
		r.reason = reason
		r.onExit(r)
		if reason == ClosePanic || reason == CloseStuck {
			r.restartOrForget()
		}
		close(r.done)
	})
}

// restartOrForget runs before the room reports being done, so anyone who notices sees its replacement already in place.
func (r *Room) restartOrForget() {
	if r.writer == nil {
		return
	}
	if r.stopReason == CloseShutdown {
		return // it got stuck while the server was stopping, so it can't restart now, but its last snapshot can next time
	}
	if r.restart == nil || !r.restart(r) {
		r.writer.forget(string(r.id))
	}
}
